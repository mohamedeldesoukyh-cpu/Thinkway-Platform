import assert from "node:assert/strict";
import { createHash, randomUUID } from "node:crypto";
import test from "node:test";
import { paymentEntryIdSchema } from "./payment-entry-id";

test("accepts manual payment IDs generated by the database's md5 UUID expression", () => {
  for (let i = 0; i < 32; i++) {
    const hash = createHash("md5").update("request-" + i + "assignment").digest("hex");
    const id = hash.replace(/^(.{8})(.{4})(.{4})(.{4})(.{12})$/, "$1-$2-$3-$4-$5");
    assert.equal(paymentEntryIdSchema.parse(id), id);
  }
});
test("accepts generated UUIDs and rejects malformed payment references", () => {
  assert.ok(paymentEntryIdSchema.safeParse(randomUUID()).success);
  for (const value of ["", "undefined", "payment-1", "00000000-0000-0000-0000-00000000000z", "../payment", null]) {
    assert.equal(paymentEntryIdSchema.safeParse(value).success, false);
  }
});
