import { writeFileSync } from "node:fs";
import puppeteer from "puppeteer-core";
import sharp from "sharp";
import { QUOTATION_LIST_REDESIGN_CSS } from "../features/quotations/export/quotation-list-redesign-styles";

// Rasterize only the transparent veil, preserving the original CSS gradient.
// Text and creator photos stay independent and sharp in the exported PDF.
async function main() {
  const browser = await puppeteer.launch({
    executablePath: process.env.CHROME_PATH ?? "C:/Program Files/Google/Chrome/Application/chrome.exe",
    headless: true,
  });
  try {
    const page = await browser.newPage();
    await page.setViewport({ width: 1600, height: 900 });
    const overlays: string[] = [];
    for (const name of ["veil", "veil--end"]) {
      const rule = QUOTATION_LIST_REDESIGN_CSS.match(new RegExp(`\\.${name}\\{([^}]+)\\}`))?.[1];
      if (!rule) throw new Error(`Missing ${name} CSS`);
      await page.setContent(`<style>html,body{margin:0;background:transparent}.overlay{position:absolute;inset:0;${rule}}</style><div class="overlay"></div>`);
      const png = await sharp(await page.screenshot({ omitBackground: true })).resize(800, 450).png({ compressionLevel: 9 }).toBuffer();
      overlays.push(`data:image/png;base64,${png.toString("base64")}`);
    }
    writeFileSync("features/quotations/export/quotation-pdf-overlay-images.ts", `// Generated by scripts/generate-quotation-pdf-overlays.ts from the preview CSS.\nexport const QUOTATION_PDF_COVER_OVERLAY = ${JSON.stringify(overlays[0])};\nexport const QUOTATION_PDF_CLOSING_OVERLAY = ${JSON.stringify(overlays[1])};\n`);
  } finally {
    await browser.close();
  }
}
void main();
