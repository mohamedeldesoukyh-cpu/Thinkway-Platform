BEGIN;
SET LOCAL statement_timeout='30s';
SET LOCAL lock_timeout='5s';
DO $$
DECLARE l campaign_lines%ROWTYPE; a campaign_influencers%ROWTYPE; v vendor_ios%ROWTYPE; actor uuid; entry uuid; next_io uuid; blocked boolean; original_amount numeric;
BEGIN
 SELECT * INTO STRICT l FROM campaign_lines WHERE vendor_io_id IS NOT NULL LIMIT 1;
 SELECT * INTO STRICT v FROM vendor_ios WHERE id=l.vendor_io_id;
 SELECT * INTO STRICT a FROM campaign_influencers WHERE id=v.assignment_id;
 SELECT created_by INTO actor FROM campaign_headers WHERE id=l.campaign_header_id;
 PERFORM set_config('request.jwt.claim.sub',actor::text,true);
 l:=jsonb_populate_record(l,jsonb_build_object('id',gen_random_uuid(),'document_number','QA-IO-REOPEN','vendor_io_id',NULL,'invoice_id',NULL,'operational_status','draft','billing_status','draft','status','draft','cost_locked',false,'revenue_locked',false,'vat_locked',false,'vendor_assignment_locked',false,'metadata',coalesce(l.metadata,'{}'::jsonb)-'pending_vendor_io_id'));
 INSERT INTO campaign_lines SELECT l.*;
 a:=jsonb_populate_record(a,jsonb_build_object('id',gen_random_uuid(),'campaign_line_id',l.id,'vendor_payment_status','unpaid'));
 INSERT INTO campaign_influencers SELECT a.*;
 UPDATE vendor_ios SET is_superseded=true WHERE id=v.id;
 v:=jsonb_populate_record(v,jsonb_build_object('id',gen_random_uuid(),'assignment_id',a.id,'document_number','QA-IO-REOPEN','root_vendor_io_id',NULL,'replaces_vendor_io_id',NULL,'is_superseded',false,'revision_number',0,'status','generated'));
 INSERT INTO vendor_ios SELECT v.*;
 UPDATE campaign_lines SET vendor_io_id=v.id,operational_status='io_generated',billing_status='moved_to_billing' WHERE id=l.id;
 INSERT INTO vendor_io_lines(vendor_io_id,campaign_line_id) VALUES(v.id,l.id);
 PERFORM set_config('request.jwt.claim.sub','',true);
 blocked:=false;
 BEGIN PERFORM reopen_vendor_ios_for_edit(l.campaign_header_id,ARRAY[v.id],'QA unauthorized');
 EXCEPTION WHEN OTHERS THEN IF SQLERRM NOT LIKE '%permission%' THEN RAISE; END IF; blocked:=true; END;
 IF NOT blocked THEN RAISE EXCEPTION 'Unauthorized reopen allowed'; END IF;
 PERFORM set_config('request.jwt.claim.sub',actor::text,true);
 INSERT INTO creator_payment_entries(campaign_id,assignment_id,io_id,creator_name,original_currency,original_amount,original_total,original_fee,vat_percent,payment_currency,exchange_rate,payment_amount,status,source,payment_date)
 VALUES(l.campaign_header_id,a.id,v.id,'QA',v.currency_code,1,v.amount,v.amount,0,v.currency_code,1,1,'paid','manual',current_date) RETURNING id INTO entry;
 blocked:=false;
 BEGIN PERFORM reopen_vendor_ios_for_edit(l.campaign_header_id,ARRAY[v.id],'QA paid block');
 EXCEPTION WHEN OTHERS THEN IF SQLERRM NOT LIKE '%clear the payment%' THEN RAISE; END IF; blocked:=true; END;
 IF NOT blocked THEN RAISE EXCEPTION 'Paid IO reopened'; END IF;
 IF (SELECT eligible FROM vendor_io_reopen_eligibility(ARRAY[v.id])) THEN RAISE EXCEPTION 'Paid IO action enabled'; END IF;
 UPDATE creator_payment_entries SET status='exported' WHERE id=entry;
 blocked:=false;
 BEGIN PERFORM reopen_vendor_ios_for_edit(l.campaign_header_id,ARRAY[v.id],'QA exported block');
 EXCEPTION WHEN OTHERS THEN IF SQLERRM NOT LIKE '%clear the payment%' THEN RAISE; END IF; blocked:=true; END;
 IF NOT blocked THEN RAISE EXCEPTION 'Exported payment reopened'; END IF;
 UPDATE creator_payment_entries SET status='paid' WHERE id=entry;
 PERFORM revise_creator_payment(entry,0,NULL,NULL,true,'QA clear payment');
 IF (SELECT cleared_at FROM creator_payment_entries WHERE id=entry) IS NULL THEN RAISE EXCEPTION 'Payment not cleared'; END IF;
 IF NOT (SELECT eligible FROM vendor_io_reopen_eligibility(ARRAY[v.id])) THEN RAISE EXCEPTION 'Cleared IO action not enabled'; END IF;
 -- Link the test assignment to an existing issued invoice: the immutable client invoice stays protected.
 UPDATE campaign_lines SET invoice_id=(SELECT id FROM invoices WHERE issue_date IS NOT NULL LIMIT 1) WHERE id=l.id;
 blocked:=false;
 BEGIN PERFORM reopen_vendor_ios_for_edit(l.campaign_header_id,ARRAY[v.id],'QA invoice block');
 EXCEPTION WHEN OTHERS THEN IF SQLERRM NOT LIKE '%client invoice%' THEN RAISE; END IF; blocked:=true; END;
 IF NOT blocked THEN RAISE EXCEPTION 'Issued invoice protection failed'; END IF;
 UPDATE campaign_lines SET invoice_id=NULL WHERE id=l.id;
 PERFORM reopen_vendor_ios_for_edit(l.campaign_header_id,ARRAY[v.id],'QA amount/currency correction');
 IF NOT (SELECT is_superseded FROM vendor_ios WHERE id=v.id) THEN RAISE EXCEPTION 'History not preserved'; END IF;
 IF (SELECT amount FROM vendor_ios WHERE id=v.id) IS DISTINCT FROM v.amount THEN RAISE EXCEPTION 'Old IO amount changed'; END IF;
 IF (SELECT vendor_io_id FROM campaign_lines WHERE id=l.id) IS NOT NULL THEN RAISE EXCEPTION 'Line not reopened'; END IF;
 UPDATE campaign_lines SET cost_before_vat=1234,cost=1234,currency_code='USD' WHERE id=l.id;
 next_io:=regenerate_reopened_vendor_io(v.id);
 IF NOT EXISTS(SELECT 1 FROM vendor_ios WHERE id=next_io AND amount=1234 AND currency_code='USD' AND replaces_vendor_io_id=v.id AND NOT is_superseded) THEN RAISE EXCEPTION 'Revision did not use edited amount/currency'; END IF;
 IF (SELECT vendor_io_id FROM campaign_lines WHERE id=l.id)<>next_io THEN RAISE EXCEPTION 'Revision not linked'; END IF;
 blocked:=false;
 BEGIN PERFORM regenerate_reopened_vendor_io(v.id);
 EXCEPTION WHEN OTHERS THEN blocked:=true; END;
 IF NOT blocked THEN RAISE EXCEPTION 'Duplicate revision allowed'; END IF;
 RAISE NOTICE 'PASS: authorization, paid block, actual clear-payment flow, reopen, edited amount/currency revision, preserved history, duplicate prevention';
END $$;
ROLLBACK;
