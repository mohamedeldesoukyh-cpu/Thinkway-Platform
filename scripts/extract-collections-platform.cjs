const fs = require('node:fs');
const path = require('node:path');
const postcss = require('postcss');
const root = path.resolve(__dirname, '..');
const names = new Set('tw-ad tw-adf tw-adh tw-adr tw-b tw-c tw-cc tw-ch tw-code tw-cs tw-ct tw-cwin tw-dc2 tw-dc2__h tw-f tw-ft tw-g tw-hint tw-hr tw-in tw-k tw-lbl tw-mast tw-mb tw-mh tw-miss tw-mr tw-ms2 tw-note tw-p tw-pad tw-po tw-r tw-rr tw-sc tw-seg tw-sp tw-st tw-t tw-v'.split(' '));
const modifiers = new Set('alert bad g go id lb msg n p-g p-y pri r s sm st sub wrn z'.split(' '));
const files = ['vendor', 'client'].map(kind => `app/styles/${kind}-detail-suite.css`);
function parse(file) {
  const text = fs.readFileSync(path.join(root, file), 'utf8');
  const rules = [];
  postcss.parse(text).walkRules(rule => {
    const raw = text.slice(rule.source.start.offset, rule.source.end.offset);
    const body = raw.slice(raw.indexOf('{'));
    const parents = [];
    for (let p = rule.parent; p?.type === 'atrule'; p = p.parent) parents.unshift(`@${p.name} ${p.params}`);
    const selected = [];
    for (const selector of rule.selectors) {
      const normalized = selector.replace(/\.(vendor|client)-detail-suite\s+/g, '');
      const classes = [...normalized.matchAll(/\.([\w-]+)/g)].map(m => m[1]);
      if (!classes.length || !classes.every(c => names.has(c) || modifiers.has(c))) continue;
      if (!names.has(classes[0]) && !['p-g', 'p-y'].includes(classes[0])) continue;
      if (rule.source.start.line > 911) continue; // Subsequent rules are page-specific adjustments.
      const shared = normalized.replace(/^\.(p-g|p-y)\b/, '.tw-p.$1');
      selected.push({ selector, normalized, shared, key: JSON.stringify([shared, body, parents]) });
    }
    if (selected.length) rules.push({ rule, raw, body, parents, selected });
  });
  return { text, rules };
}
const vendor = parse(files[0]);
const client = parse(files[1]);
const clientKeys = new Set(client.rules.flatMap(r => r.selected.map(s => s.key)));
const sharedRules = vendor.rules.map(r => ({ ...r, selected: r.selected.filter(s => clientKeys.has(s.key)) })).filter(r => r.selected.length);
const guard = '.collections-suite ';
const emitted = new Set();
const chunks = [];
const manifest = [];
for (const r of sharedRules) {
  const selected = r.selected.filter(s => !emitted.has(s.key));
  if (!selected.length) continue;
  selected.forEach(s => emitted.add(s.key));
  let css = selected.map(s => guard + s.shared).join(',\n') + r.body;
  for (const p of [...r.parents].reverse()) css = `${p}{\n${css}\n}`;
  chunks.push(css);
  manifest.push({ source: files[0], line: r.rule.source.start.line, selectors: selected.map(s => s.shared), body: r.body, parents: r.parents });
}
const output = '/* Component declarations copied verbatim from vendor/client suites.\n * Collections-only scope: source pages and other modules are unchanged.\n * Generated by scripts/extract-collections-platform.cjs. */\n' + chunks.join('\n') + '\n';
fs.writeFileSync(path.join(root, 'app/styles/collections-platform-shared.css'), output);
fs.mkdirSync(path.join(root, 'docs/validation-artifacts/collections-redesign'), { recursive: true });
fs.writeFileSync(path.join(root, 'docs/validation-artifacts/collections-redesign/extraction-manifest.json'), JSON.stringify(manifest, null, 2));
const present = new Set(manifest.flatMap(r => r.selectors.flatMap(s => [...s.matchAll(/\.(tw-[\w-]+)/g)].map(m => m[1]))));
console.log(JSON.stringify({ rules: manifest.length, missing: [...names].filter(n => !present.has(n)) }, null, 2));
