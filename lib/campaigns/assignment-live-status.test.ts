import assert from "node:assert/strict";
import { assignmentHasGoneLive } from "./assignment-live-status";
const today = "2026-10-25";
assert.equal(assignmentHasGoneLive({}, [{ workflow_status: "draft", live_date: "2026-08-14", posts: [] }], today), true);
assert.equal(assignmentHasGoneLive({}, [{ workflow_status: "draft", posts: [{ live_date: "2026-08-14", workflow_status: "draft" }] }], today), true);
assert.equal(assignmentHasGoneLive({}, [{ workflow_status: "posted" }], today), true);
assert.equal(assignmentHasGoneLive({}, [{ workflow_status: "verified" }], today), true);
assert.equal(assignmentHasGoneLive({ went_live_date: "2026-10-22" }, [], today), true);
assert.equal(assignmentHasGoneLive({}, [{ workflow_status: "draft", live_date: null }], today), false);
assert.equal(assignmentHasGoneLive({}, [{ workflow_status: "scheduled", live_date: "2026-11-01" }], today), false);
assert.equal(assignmentHasGoneLive({}, [{ live_date: "invalid" }, { live_date: " " }], today), false);
console.log("assignment-live-status: all checks passed");
